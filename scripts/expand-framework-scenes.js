const map = Object.fromEntries(dash.posts.map((p) => [p.i, p]));
const themeName = Object.fromEntries(dash.themes.map((t) => [t.code, t.name]));
const srcLabel = (s) => (dash.sources[s] && dash.sources[s].label) || s;

function C(id, maxLen = 220) {
  const p = map[id];
  if (!p) throw new Error('missing ' + id);
  const text = (p.t || '').replace(/\s+/g, ' ').trim().slice(0, maxLen);
  return {
    text: text + (text.length >= maxLen ? '…' : ''),
    url: p.u || '',
    source: srcLabel(p.s),
    theme: p.th || '',
    id: p.i,
  };
}
function act(id, name, pain, caseIds, primary = true) {
  return { id, name, primary, pain, cases: caseIds.map((cid) => C(cid)) };
}
function ty(type, dim, situation, pain, actions) {
  return { type, dim, situation, pain, actions };
}

