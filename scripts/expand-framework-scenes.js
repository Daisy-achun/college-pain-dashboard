function upsert(stageId, scenes) {
  const st = F.stages[stageId];
  const byId = Object.fromEntries(st.scenes.map((s) => [s.id, s]));
  for (const sc of scenes) byId[sc.id] = sc;
  // preserve order: existing first (minus removed), then new ids in given order
  const order = scenes.map((s) => s.id);
  const rest = st.scenes.filter((s) => !order.includes(s.id));
  st.scenes = [...scenes.map((id) => byId[id.id]), ...rest.filter((s) => !scenes.find((x) => x.id === s.id))];
  // Actually we want full ordered list from `scenes` argument as the complete set
  st.scenes = scenes.map((s) => byId[s.id] || s);
}

